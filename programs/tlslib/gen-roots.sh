#!/usr/bin/env bash
#
# Make src/roots.c (the trust anchors built into the tls library) from a
# PEM file of root certificates, default mozilla-roots.pem:
#
#   bash gen-roots.sh [roots.pem]
#
# mozilla-roots.pem is Ubuntu's ca-certificates 20260816 (the Mozilla root
# program): /usr/share/ca-certificates/mozilla/*.crt put together. Take
# them from there again, or from curl's cacert.pem, to update them.
#
# Uses BearSSL's own "brssl ta", built here for this machine from
# bearssl/ (needs a host C compiler, cc).
#
set -euo pipefail
cd "$(dirname "$0")"
PEM=${1:-mozilla-roots.pem}
HOSTCC=${HOSTCC:-cc}

TOOL=build-host/brssl
if [ ! -x "$TOOL" ]; then
    mkdir -p build-host
    $HOSTCC -O1 -w -Ibearssl/inc -Ibearssl/src -o "$TOOL" \
        bearssl/tools/*.c $(find bearssl/src -name '*.c')
fi

{
    echo "/*"
    echo " * The trust anchors built into the tls library: generated by gen-roots.sh"
    echo " * from $PEM with BearSSL's \"brssl ta\". Don't edit by hand."
    echo " */"
    echo
    echo '#include "bearssl.h"'
    "$TOOL" ta "$PEM" | sed -e 's/^static const br_x509_trust_anchor TAs\[/const br_x509_trust_anchor TAs[/'
    echo
    echo "const size_t TAs_NUM_VALUE = TAs_NUM;"
} > src/roots.c.new
mv src/roots.c.new src/roots.c
echo "gen-roots: $(grep -c 'BEGIN CERTIFICATE' "$PEM") roots into src/roots.c"
