#define HELLO_ELF_SIZE  ((uint32_t)sizeof(hello_elf))

_Static_assert(sizeof(hello_elf) == 496, "hello_elf size");

// Write hello_elf to `path` (absolute, on a mounted device, e.g.
// "/mnt/ata0p1/usr/desktop/hello") and mark it executable. Overwrites an
// existing file. Thread context only (VFS). Returns true on success.
static inline bool hello_elf_drop(const char* path) {
    // Create it if missing, then size it before writing: writes don't
    // reliably extend a file (same sequence as dwm_desktop_layout_save)
    File file = vfs_open(path, VFS_OPEN_CREATE | VFS_OPEN_READ | VFS_OPEN_WRITE);
    if (file == VFS_INVALID_FILE) return false;
    vfs_close(file);

    if (!vfs_truncate(path, HELLO_ELF_SIZE)) return false;

    file = vfs_open(path, VFS_OPEN_READ | VFS_OPEN_WRITE);
    if (file == VFS_INVALID_FILE) return false;

    vfs_seek(file, 0);
    uint32_t done = 0;
    while (done < HELLO_ELF_SIZE) {
        int32_t n = vfs_write(file, hello_elf + done, HELLO_ELF_SIZE - done);
        if (n <= 0) break;
        done += (uint32_t)n;
    }
    vfs_close(file);
    if (done != HELLO_ELF_SIZE) return false;

    return vfs_set_permissions(path, VFS_PERMISSION_READ | VFS_PERMISSION_WRITE | VFS_PERMISSION_EXECUTE);
}

